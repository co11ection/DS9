# 1. Описание проекта
# Нужно разработать приложение реального времени, которое открывает камеру и одновременно делает две вещи: находит лицо в кадре и помечает его рамкой с подписью, а поднятая перед камерой рука служит «пером» — рисует линию на отдельном холсте, который накладывается поверх видео. Один поднятый палец рисует, два пальца меняют цвет линии, кулак (0 пальцев) очищает холст, а клавиша сохраняет готовый рисунок в файл.
# Жесты управления
# Жест / клавиша	Действие
# 1 палец поднят	рисовать линию текущим цветом, следуя за кончиком пальца
# Палец опущен / рука не в кадре	«перо поднято» — линия не рисуется
# 2 пальца	сменить цвет линии (по кругу из нескольких цветов)
# Кулак (0 пальцев)	полностью очистить холст
# Клавиша 's'	сохранить текущий кадр с рисунком в файл
# Клавиша 'q'	завершить программу

# Важная деталь, из-за которой этот проект не сводится к простому копированию кода из «Урока 29» и «Урока 30» рядом друг с другом: лицо и шея человека — это ТОЖЕ кожа, и в HSV почти всегда попадают в тот же диапазон оттенков, что и ладонь. Если искать руку по маске кожи, не трогая область лица, самым большим контуром на кадре нередко окажется лицо, а не рука — поиск руки нужно явно защитить от этой ошибки (подробнее — в разделе 3.2).


