#Основные понятия
# класс - шаблон обьекта
# обьект - экземпляр класса
# атрибут - данные обьекта - переменные
# методы - действия - функция


class Student:
    def __init__(self, name, age): # Создание атрибутов(инициолизирование)
        # self- ссылка на обьект
        self.name = name # Атрибуты
        self.age = age
    
    def study(self): # Метод
        return f"{self.name} учится"

student1 = Student('Aktan', 20) # Создание обьекта 
student2 = Student('Almaz', 23)

print(student1.name)  
print(student1.study())  
print(student2.name)  


