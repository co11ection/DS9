""" 
Атрибуты:
Атрибуты обьекта - то что есть у самого обьекта
Атрибуты класса - относится ко всему классу
"""

class Student:
    course_name = "Ai Academy" # Атрибут класса
    student_count = 0
    def __init__(self, name, age): # Создание атрибутов(инициолизирование)
        # self- ссылка на обьект
        self.name = name # Атрибуты обьекта
        self.age = age
        Student.student_count += 1 # Увеличииваем счетчик студентов
    
    def study(self): # Метод
        return f"{self.name} учится"
    
    def __str__(self): # Для отображения обьекта
        return f"{self.name} --- {self.age}"
    
student1 = Student('Aktan', 20)
student2 = Student('Almaz', 23)

print(student1.student_count)
print(student2.student_count)

